/** Build-time only: preserve the public plugin's complete published reference data. */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export async function bundleClawdReference({ sourceRoot, packageRoot, check = false }) {
  const skillsRoot = join(sourceRoot, 'agent', 'skills');
  const guides = {};
  const skills = [];
  for (const entry of readdirSync(skillsRoot, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (!entry.isDirectory() || !existsSync(join(skillsRoot, entry.name, 'SKILL.md'))) continue;
    if (!/^[a-z0-9-]{1,96}$/.test(entry.name)) throw new Error('Invalid bundled guide ID');
    const body = readFileSync(join(skillsRoot, entry.name, 'SKILL.md'), 'utf8');
    const frontmatter = /^---\n([\s\S]*?)\n---/.exec(body)?.[1] ?? '';
    const metadata = {};
    for (const line of frontmatter.split('\n')) {
      const separator = line.indexOf(':');
      if (separator <= 0) continue;
      const key = line.slice(0, separator).trim();
      if (key === 'name' || key === 'description') metadata[key] = line.slice(separator + 1).trim().replace(/^["']|["']$/g, '');
    }
    guides[entry.name] = body;
    skills.push({ id: entry.name, name: metadata.name || entry.name, description: metadata.description || '', path: `agent/skills/${entry.name}/SKILL.md` });
  }
  // Only the pure fee-table export is called. This import exists in this build
  // script; the generated runtime module has no Solana or filesystem dependency.
  const { documentedFeeTiersMarkdown } = await import(pathToFileURL(join(sourceRoot, 'src', 'fees.ts')).href);
  const data = {
    feeTiersMarkdown: documentedFeeTiersMarkdown(),
    registry: {
      schema_version: 'v1',
      name: 'pump-mcp',
      description: 'Bundled Cheshire, Clawd, DFlow, Helius, Imperial, and Pump.fun skills for PUMP-MCP + CLAWD free router',
      skills,
    },
    guides,
  };
  if (skills.length !== 57) throw new Error(`Expected the complete 57-guide catalog, found ${skills.length}`);
  const target = join(packageRoot, 'src', 'shared', 'clawd-reference-data.ts');
  const output = '// Generated by scripts/bundle-clawd-reference.mjs from PUMP-MCP-main public references.\n'
    + "import type { ClawdReferenceData } from './clawd-reference-types.js';\n\n"
    + `export const bundledClawdReferenceData: ClawdReferenceData = ${JSON.stringify(data, null, 2)};\n`;
  if (check) {
    if (readFileSync(target, 'utf8') !== output) throw new Error('Clawd reference bundle differs from its public source');
  } else writeFileSync(target, output);
  return { guides: skills.length, bytes: Buffer.byteLength(output), checked: check };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const sourceRoot = [resolve(packageRoot, '../PUMP-MCP-main'), resolve(packageRoot, '../../PUMP-MCP-main')]
    .find((candidate) => existsSync(join(candidate, 'src', 'plugin.ts')));
  if (!sourceRoot) throw new Error('PUMP-MCP-main public reference source is unavailable');
  console.log(JSON.stringify(await bundleClawdReference({ sourceRoot, packageRoot, check: process.argv.includes('--check') })));
}
